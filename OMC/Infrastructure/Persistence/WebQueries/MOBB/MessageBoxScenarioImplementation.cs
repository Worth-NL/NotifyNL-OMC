        /// <summary>
        /// Fetches document metadata for attachments (bijlagen) from the Documenten API.
        /// Walks the attachments in order (there is no priority/ordering field, so the source's own
        /// order is trusted) and stops as soon as <see cref="MaxAttachments"/> usable ones are collected,
        /// so an invalid or ignorable entry doesn't cost a slot that a later, valid attachment could fill.
        /// </summary>
        /// <param name="queryContext">The query context for retrieving document metadata.</param>
        /// <param name="attachments">The list of attachments from the VTB message.</param>
        /// <returns>A list of <see cref="SingularInformationObject"/> containing document metadata.</returns>
        /// <summary>
        /// <see cref="FetchAttachmentsAsync"/>, traced as a call to the Documenten API — only when the
        /// Bericht has attachments at all, so a Bericht without any doesn't show a call that never happens.
        /// </summary>
        private async Task<List<SingularInformationObject>> FetchAttachmentsWithTraceAsync(
            IQueryContext queryContext,
            VtbMessage.Attachment[]? attachments)
        {
            if (attachments is not { Length: > 0 })
            {
                return [];
            }

            TraceContext.Emit("documenten", "start", $"Attempting to retrieve {attachments.Length} attachment(s)");
            List<SingularInformationObject> documents = await FetchAttachmentsAsync(queryContext, attachments);
            TraceContext.Emit("documenten", "ok", $"{documents.Count} attachment(s) retrieved");

            return documents;
        }

        private async Task<List<SingularInformationObject>> FetchAttachmentsAsync(
            IQueryContext queryContext,
            VtbMessage.Attachment[]? attachments)
        {
            var documents = new List<SingularInformationObject>();

            if (attachments == null || attachments.Length == 0)
                return documents;

            foreach (VtbMessage.Attachment attachment in attachments)
            {
                if (documents.Count == MaxAttachments)
                    break;

                // Standard pre-uploaded attachments are not meant for the Berichtenbox
                if (attachment.IsMessageTypeAttachment)
                    continue;

                if (string.IsNullOrEmpty(attachment.InformationObjectUrn))
                    continue;

                Guid? documentUuid = ExtractUuidFromUrn(attachment.InformationObjectUrn);
                if (!documentUuid.HasValue)
                    continue;

                try
                {
                    // Fetch document metadata from Documenten API
                    SingularInformationObject document = await queryContext.GetDocumentAsync(documentUuid.Value);

                    // "inhoud" is a download link on GET, not the file content itself (confirmed against
                    // the live Documenten API - see SingularInformationObject.Content's remarks), so the
                    // actual bytes need a second, explicit fetch before this is usable as a Notify attachment.
                    if (!string.IsNullOrEmpty(document.Content))
                    {
                        document.Content = await queryContext.GetDocumentContentAsync(new Uri(document.Content));
                    }

                    documents.Add(document);
                }
                catch (Exception exception)
                {
                    _logger.LogWarning(exception,
                        "Skipping attachment {DocumentUuid}: failed to fetch or resolve its content.", documentUuid);
                }
            }

            return documents;
        }

        /// <summary>
        /// Extracts a 9-digit BSN from a recipient URN string.
        /// Assumes the URN contains a ':bsn:XXXXXXXXX' segment.
        /// </summary>
        private static string? ExtractBsnFromUrn(string urn)
        {
            if (string.IsNullOrEmpty(urn))
                return null;

            string[] segments = urn.Split(':');
            for (int i = 0; i < segments.Length - 1; i++)
            {
                if (string.Equals(segments[i], "bsn", StringComparison.OrdinalIgnoreCase) &&
                    Regex.IsMatch(segments[i + 1], "^[0-9]{9}$"))
                {
                    return segments[i + 1];
                }
            }

            return null;
        }

        /// <summary>
        /// Extracts a UUID from a URN string.
        /// Assumes the URN ends with ':uuid:XXXXXXXX-XXXX-XXXX-XXXX-XXXXXXXXXXXX'.
        /// </summary>
        private static Guid? ExtractUuidFromUrn(string urn)
        {
            if (string.IsNullOrEmpty(urn))
                return null;

            string[] segments = urn.Split(':');
            for (int i = 0; i < segments.Length - 1; i++)
            {
                if (segments[i] == "uuid")
                {
                    string uuidStr = segments[i + 1];
                    if (Guid.TryParse(uuidStr, out Guid uuid))
                        return uuid;
                }
            }

            return null;
        }

